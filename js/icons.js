function iconSVG(name, className) {
    if (!ICONS[name]) return '';
    var cls = className ? ' class="' + className + '"' : '';
    return '<svg' + cls + ' viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + ICONS[name] + '</svg>';
}

function renderIcons(root) {
    if (!root) root = document;
    root.querySelectorAll('[data-icon]').forEach(function(el) {
        el.innerHTML = iconSVG(el.dataset.icon);
    });
}

document.addEventListener('DOMContentLoaded', function() { renderIcons(document); });

function showToast(message) {
    var existing = document.querySelector('.toast');
    if (existing) existing.remove();
    var toast = document.createElement('div');
    toast.className = 'toast';
    toast.textContent = message;
    toast.setAttribute('role', 'alert');
    document.body.appendChild(toast);
    requestAnimationFrame(function() { toast.classList.add('show'); });
    setTimeout(function() {
        toast.classList.remove('show');
        setTimeout(function() { toast.remove(); }, 300);
    }, 3000);
}